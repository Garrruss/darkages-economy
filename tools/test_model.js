// Проверка модели казны. Запуск из папки сайта: node tools/test_model.js
// Берёт функцию simulate из model.html и сверяет с расчётом, сделанным вручную по правилам страницы.
const fs = require("fs"), path = require("path");
const html = fs.readFileSync(path.join(__dirname, "..", "model.html"), "utf8");
const m = html.match(/\/\/ BEGIN-SIM([\s\S]*?)\/\/ END-SIM/);
if (!m) { console.error("нет блока BEGIN-SIM"); process.exit(1); }
const simulate = new Function(m[1] + "; return simulate;")();
const base = {seed: 2000, P: 25, D: 8, fill: 100, prod: 3, auto: 0, autoDays: 0, danger: 0, barren: 0, orders: 0, other: 0, levy: 0, payers: 0};
let bad = 0;
function check(name, got, want) {
  const ok = JSON.stringify(got) === JSON.stringify(want);
  if (!ok) { bad++; console.log("ОШИБКА", name, "получено", JSON.stringify(got), "ожидалось", JSON.stringify(want)); }
  else console.log("ok", name);
}
const pick = (rows, keys) => rows.map(r => keys.map(k => r[k]));

// 1. Без разбоя и дополнительных доходов, подмога 150: казна падает на 310 в день.
// Ручной расчёт: день 0: 2000-460=1540; дни 1-4: 1230, 920, 610, 300.
// День 5: 300+150=450 < 460, недоимка: ссуда 1000, остаток 990, долг 1000.
// День 6: подмога на долг (850), остаток 990-460=530. День 7: долг 700, остаток 70.
// День 8: долг 550, остаток 70 < 460, опись: остаток 2500, долг 550+5000=5550, жалованье не платится.
let r = simulate(Object.assign({}, base)).rows;
check("сценарий 1: казна по дням", pick(r, ["fund"]).map(x => x[0]), [1540, 1230, 920, 610, 300, 990, 530, 70, 2500]);
check("сценарий 1: долг по дням", pick(r, ["debt"]).map(x => x[0]), [0, 0, 0, 0, 0, 1000, 850, 700, 5550]);
check("сценарий 1: состояние на днях 5 и 8", [r[5].state, r[8].state], ["недоимка", "опись"]);
check("сценарий 1: жалованье на день 8", r[8].paid, 0);

// 2. Разбой по умолчанию: 2 опасные и 1 безнадёжная земля при P=25: 2*65 + 130 = 260 в день, подмога 100.
// Ручной расчёт: день 0: 1540. День 1: приток 100, жалованье, остаток 1180; разбой не сжигает (ниже 1500), долг по разбою 260.
// День 2: из 100 на долг по разбою 75, в кошелёк 25: 1205, жалованье: 745, долг по разбою 185+260=445.
// День 3: 75 на долг (370), в кошелёк 25: 770, жалованье: 310, долг по разбою 630.
// День 4: 75 на долг (555), в кошелёк 25: 335 < 460, недоимка: ссуда 1000, 1335, жалованье: 875, долг казны 1000, долг по разбою 815.
// День 5: 75 на разбой (740), 25 на долг казны (975), остаток 875, жалованье: 415, долг по разбою 1000.
// День 6: 75 на разбой (925), 25 на долг казны (950), остаток 415 < 460, опись: остаток 2500, долг 950+5000=5950;
// разбой сжигает 260 (2500-1500=1000 хватает): 2240, долг по разбою 925.
r = simulate(Object.assign({}, base, {prod: 6, danger: 2, barren: 1, D: 6})).rows;
check("сценарий 2: казна", r.map(x => x.fund), [1540, 1180, 745, 310, 875, 415, 2240]);
check("сценарий 2: долг казны", r.map(x => x.debt), [0, 0, 0, 0, 1000, 975, 5950]);
check("сценарий 2: долг по разбою", r.map(x => x.bdebt), [0, 260, 445, 630, 815, 1000, 925]);
check("сценарий 2: состояние на днях 4 и 6", [r[4].state, r[6].state], ["недоимка", "опись"]);

// 3. Выход из недоимки: начальная казна 100 меньше жалованья, ссуда 1000 на день 0, затем крупный приток гасит долг.
// День 0: 100+1000=1100, жалованье: 640, долг 1000. День 1: приток 100+2000=2100: 1000 на долг, 1100 в кошелёк: 1740, жалованье: 1280.
r = simulate(Object.assign({}, base, {seed: 100, prod: 6, other: 2000, D: 1})).rows;
check("сценарий 3: казна", r.map(x => x.fund), [640, 1280]);
check("сценарий 3: долг", r.map(x => x.debt), [1000, 0]);
check("сценарий 3: состояние", r.map(x => x.state), ["недоимка", "нормально"]);

// 4. Начальная казна не зависит от числа игроков (надбавки «35 на игрока» нет).
const a = simulate(Object.assign({}, base, {P: 0, D: 1})).rows[0].fund, b = simulate(Object.assign({}, base, {P: 80, D: 1})).rows[0].fund;
check("сценарий 4: казна на старте не зависит от P", [a, b], [1540, 1540]);

// 5. Подушная подать: дни 2 и 4, 20 монет с 10 плательщиков = 200 к притоку.
r = simulate(Object.assign({}, base, {prod: 6, levy: 20, payers: 10, D: 4})).rows;
check("сценарий 5: приток по дням", r.map(x => x.inc), [0, 100, 300, 100, 300]);

console.log(bad ? "ПРОВАЛ: " + bad : "ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ");
process.exit(bad ? 1 : 0);
